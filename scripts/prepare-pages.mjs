import { cp, readFile, rm, writeFile } from 'node:fs/promises';

const project = new URL('../', import.meta.url);
const dist = new URL('dist/', project);
const generatedFiles = ['favicon.png', 'pelican-poster.webp'];
const assets = new URL('pages-assets/', project);

const html = await readFile(new URL('index.html', dist), 'utf8');
await rm(assets, { recursive: true, force: true });
await Promise.all([
  cp(new URL('pages-assets/', dist), assets, { recursive: true }),
  ...generatedFiles.map((file) => cp(new URL(file, dist), new URL(file, project))),
]);
await Promise.all([
  writeFile(new URL('index.html', project), '<!-- Generated by npm run prepare:pages. Edit game/index.html. -->\n' + html),
  writeFile(new URL('.nojekyll', project), ''),
]);
